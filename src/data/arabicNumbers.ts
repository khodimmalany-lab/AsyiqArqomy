export function toArabicDigits(num: number): string {
  const map = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(Math.max(0, Math.floor(num)))
    .split('')
    .map((ch) => (ch >= '0' && ch <= '9' ? map[Number(ch)] : ch))
    .join('');
}

